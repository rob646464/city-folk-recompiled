#!/usr/bin/env python3
"""Write docs/SDK_NAMES.md: the HLE-relevant SDK functions (tools/discovery/hle_wanted.txt)
with their addresses in each version, and what is still missing.

    python tools/discovery/sdk_report.py [--ids RUUE01,RUUP01,RUUJ01]
"""
import argparse
from collections import Counter, OrderedDict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def wanted():
    groups = OrderedDict()
    cur = None
    for ln in (HERE / "hle_wanted.txt").read_text(encoding="utf-8").splitlines():
        ln = ln.strip()
        if not ln or ln.startswith("#"):
            continue
        if ln.startswith("["):
            cur = ln.strip("[]")
            groups[cur] = []
            continue
        for tok in ln.split():
            groups[cur].append((tok.rstrip("?"), tok.endswith("?")))
    return groups


def load(id_):
    p = ROOT / "config" / id_ / "names.txt"
    out = {}
    if not p.exists():
        return out
    import sys
    sys.path.insert(0, str(HERE))
    import symfile
    for s in symfile.parse(ROOT / "config" / id_ / "symbols.txt"):
        if s.type == "label" and s.section in (".text", ".init") and not s.name.startswith("entry_"):
            out.setdefault(s.name, (s.addr, "dtk"))
    for ln in p.read_text(encoding="utf-8").splitlines():
        q = ln.split()
        if len(q) >= 4 and not ln.startswith("#") and q[0] == "dol":
            out.setdefault(q[2], (int(q[1], 16), q[3]))
    return out


def make_diag(refdir, base):
    """Where a missing name would sit: between which of our named functions the
    references place it, and how many unnamed functions are there."""
    import sys
    sys.path.insert(0, str(HERE))
    import sdk_names
    import symfile
    syms = symfile.parse(ROOT / "config" / base / "symbols.txt")
    ours = sorted((s.addr, s.size or 0, s.name) for s in syms if s.is_func)
    pos = {}
    for i, (_, _, n) in enumerate(ours):
        pos.setdefault(n, i)
    refs = [sdk_names.Ref(n, Path(refdir) / n) for n in sdk_names.REFS if (Path(refdir) / n / "symbols.txt").exists()]

    def diag(name):
        for ref in refs:
            j = ref.index.get(name)
            if j is None:
                continue
            lo = next((k for k in range(j - 1, max(-1, j - 30), -1) if ref.funcs[k][1] in pos), None)
            hi = next((k for k in range(j + 1, min(len(ref.funcs), j + 30)) if ref.funcs[k][1] in pos), None)
            if lo is None or hi is None:
                continue
            il, ih = pos[ref.funcs[lo][1]], pos[ref.funcs[hi][1]]
            if not 0 < ih - il < 40:
                continue
            between = [o for o in ours[il + 1:ih]]
            if not between:
                return f"not linked: {ref.funcs[lo][1][:40]} and {ref.funcs[hi][1][:40]} are adjacent here ({ref.name})"
            unnamed = [f"{o[0]:08X}(0x{o[1]:X})" for o in between if sdk_names.GENERIC.match(o[2])]
            if not unnamed:
                return (f"not linked: the functions between {ref.funcs[lo][1][:40]} and {ref.funcs[hi][1][:40]} "
                        f"all have other names ({ref.name})")
            return (f"candidates between {ref.funcs[lo][1][:40]} and {ref.funcs[hi][1][:40]}: "
                    f"{' '.join(unnamed)} (ref size 0x{ref.funcs[j][0]:X}, {ref.name})")
        return "no reference places it"
    return diag


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ids", default="RUUE01,RUUP01,RUUJ01")
    ap.add_argument("--refs", help="reference maps dir (sdk_names.py): diagnoses missing names")
    a = ap.parse_args()
    ids = [i for i in a.ids.split(",") if (ROOT / "config" / i / "names.txt").exists()]
    names = {i: load(i) for i in ids}
    base = ids[0]
    g = wanted()
    diag = make_diag(a.refs, base) if a.refs else None
    out = ["# SDK function names for HLE",
           "",
           "Generated by `tools/discovery/sdk_report.py` from `config/<id>/names.txt` and the wish list",
           "`tools/discovery/hle_wanted.txt` (the functions the HLE layer is expected to replace or hook,",
           "from LM's HLE set mapped to the RVL SDK). How the names are found: docs/DISCOVERY.md \"Names\".",
           "",
           "Confidence: `dtk` = decomp-toolkit signature (instruction pattern); `high` = run of equal",
           "function sizes in link order with a reference map; `mid` = same slot as a reference",
           "function between two size-matched neighbours, own size differs (another SDK revision);",
           "`gap` = same position between two named functions in a reference with the same number",
           "of functions in between; `str` = the function's own \"X() was called\" trace string;",
           "`manual` = config/<id>/names_manual.txt; `map` = carried over from the USA table by",
           "function matching (PAL/Japan, tools/discovery/version_map.py).",
           ""]
    summ = []
    body = []
    for grp, items in g.items():
        req = [n for n, opt in items if not opt]
        found_req = [n for n in req if n in names[base]]
        opt = [n for n, o in items if o]
        found_opt = [n for n in opt if n in names[base]]
        summ.append(f"| {grp} | {len(found_req)}/{len(req)} | {len(found_opt)}/{len(opt)} |")
        body += [f"## {grp}", ""]
        hdr = "| Function | " + " | ".join(ids) + " | confidence |"
        body += [hdr, "|" + "---|" * (len(ids) + 2)]
        for n, o in items:
            if n not in names[base] and o:
                continue
            cells = []
            for i in ids:
                v = names[i].get(n)
                cells.append(f"`{v[0]:08X}`" if v else "**missing**")
            conf = names[base].get(n, (0, "-"))[1]
            body.append(f"| {n}{' (optional)' if o else ''} | " + " | ".join(cells) + f" | {conf} |")
        for n in req:
            if n not in names[base] and diag is not None:
                body.append(f"| {n} | {diag(n)} |" + " |" * (len(ids)))
        miss_opt = [n for n in opt if n not in names[base]]
        if miss_opt:
            body += ["", "Optional, not found (probably not linked, or still unnamed): " + ", ".join(miss_opt)]
        body.append("")
    out += ["## Summary (USA)", "", "| Library | required found | optional found |", "|---|---|---|"] + summ + [""]
    # all named functions per unit directory
    p = ROOT / "config" / base / "names.txt"
    cnt = Counter()
    conf = Counter()
    for ln in p.read_text(encoding="utf-8").splitlines():
        q = ln.split()
        if len(q) >= 6 and not ln.startswith("#") and q[0] == "dol":
            d = q[5].rsplit("/", 1)[0] if "/" in q[5] else (q[5] if q[5] != "-" else "(no unit)")
            cnt[d] += 1
            conf[q[3]] += 1
    out += [f"All named DOL functions ({base}): {sum(cnt.values())}; by confidence: "
            + ", ".join(f"{k} {v}" for k, v in conf.most_common()) + ".", "",
            "| Unit directory | named functions |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in cnt.most_common()] + [""]
    out += body
    (ROOT / "docs" / "SDK_NAMES.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(summ))


if __name__ == "__main__":
    main()
