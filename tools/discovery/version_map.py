#!/usr/bin/env python3
"""Carry the USA names to another version (PAL RUUP01, Japan RUUJ01, Korea RUUK01) by function matching.

    python tools/discovery/version_map.py --base-disc "US DATA/DATA" --disc "PAL DATA/DATA" --id RUUP01

Like LM's tools/recomp/gen_version_map.py: both versions' function tables come from
discover.py; every function is fingerprinted by its instructions with addresses masked
(branch targets, 16-bit immediates of addi/lis/ori and of loads/stores, which hold
relocated or r13/r2-relative addresses). The two function lists keep their link order,
so they are aligned as sequences (difflib on the fingerprints): equal runs pair as `hash`;
a changed run of the same length on both sides pairs in order as `order`; other changed
runs pair by equal size in order (`size`). RELs are matched module by module the same way.

Writes, in config/<id>/:
  names.txt     the USA names of the matched DOL functions (confidence `map`), plus this
                version's own decomp-toolkit names;
  us_map.txt    every matched DOL function: <this addr> <USA addr> <method> <name>;
  rels_us_map.txt  every matched REL function: <module> <this offset> <USA offset> <method>.
Prints the coverage.
"""
import argparse
import difflib
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))

import symfile  # noqa: E402
from ppc import Dol, Rel, be32  # noqa: E402

GENERIC = ("fn_", "lbl_", "entry_")


def mask(w):
    op = w >> 26
    if op == 18:  # b/bl
        return w & 0xFC000003
    if op in (14, 15, 24, 25) or 32 <= op <= 55:
        return w & 0xFFFF0000
    return w


def fingerprint(read, start, size):
    return hash(tuple(mask(read(a)) for a in range(start, start + size, 4)))


def align(a_fp, b_fp, a_sz, b_sz):
    """Return [(index in a, index in b, method)]"""
    sm = difflib.SequenceMatcher(None, a_fp, b_fp, autojunk=False)
    pairs = []
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == "equal":
            pairs += [(i1 + k, j1 + k, "hash") for k in range(i2 - i1)]
        elif tag == "replace":
            if i2 - i1 == j2 - j1:
                pairs += [(i1 + k, j1 + k, "order") for k in range(i2 - i1)]
            else:
                sm2 = difflib.SequenceMatcher(None, a_sz[i1:i2], b_sz[j1:j2], autojunk=False)
                for t2, x1, x2, y1, y2 in sm2.get_opcodes():
                    if t2 == "equal":
                        pairs += [(i1 + x1 + k, j1 + y1 + k, "size") for k in range(x2 - x1)]
    return pairs


def funcs_of(path, sections):
    syms = symfile.parse(path)
    return sorted((s.addr, s.size or 0, s.name) for s in syms if s.is_func and s.section in sections)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base-disc", required=True)
    ap.add_argument("--base-id", default="RUUE01")
    ap.add_argument("--disc", required=True)
    ap.add_argument("--id", required=True)
    a = ap.parse_args()
    bcfg, cfg = ROOT / "config" / a.base_id, ROOT / "config" / a.id
    bdol, dol = Dol(Path(a.base_disc) / "sys" / "main.dol"), Dol(Path(a.disc) / "sys" / "main.dol")
    bf = funcs_of(bcfg / "symbols.txt", (".text", ".init"))
    f = funcs_of(cfg / "symbols.txt", (".text", ".init"))
    bfp = [fingerprint(bdol.word, s, n) for s, n, _ in bf]
    fp = [fingerprint(dol.word, s, n) for s, n, _ in f]
    pairs = align(bfp, fp, [x[1] for x in bf], [x[1] for x in f])
    # names
    bnames = {}
    for ln in (bcfg / "names.txt").read_text(encoding="utf-8").splitlines():
        q = ln.split()
        if len(q) >= 4 and not ln.startswith("#") and q[0] == "dol":
            bnames[int(q[1], 16)] = (q[2], q[3], q[5] if len(q) > 5 else "-")
    out = ["# <module> <addr> <name> <confidence> <sources> <translation unit>",
           f"# Generated by tools/discovery/version_map.py from config/{a.base_id}/names.txt."]
    mp = [f"# <{a.id} addr> <{a.base_id} addr> <method: hash|order|size> <name>"]
    meth = Counter()
    named_mapped = Counter()
    have = set()
    for i, j, m in pairs:
        meth[m] += 1
        ba, ta = bf[i][0], f[j][0]
        nm = bnames.get(ba)
        mp.append(f"{ta:08X} {ba:08X} {m} {nm[0] if nm else bf[i][2]}")
        if nm:
            out.append(f"dol {ta:08X} {nm[0]} map {a.base_id}:{nm[1]}:{m} {nm[2]}")
            named_mapped[nm[1]] += 1
            have.add(ta)
    # this version's own dtk names where the map has none
    for s, n, name in f:
        if s not in have and not name.startswith(GENERIC):
            out.append(f"dol {s:08X} {name} dtk dtk -")
    (cfg / "names.txt").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    (cfg / "us_map.txt").write_text("\n".join(mp) + "\n", encoding="utf-8", newline="\n")
    tot_named = Counter(v[1] for v in bnames.values())
    print(f"{a.id} DOL: {len(pairs)}/{len(f)} functions matched to {a.base_id} ({len(bf)}): {dict(meth)}")
    print(f"  names carried: {sum(named_mapped.values())}/{len(bnames)} "
          + ", ".join(f"{k} {named_mapped[k]}/{v}" for k, v in tot_named.most_common()))
    unm = [bnames[bf[i][0]][0] for i in range(len(bf)) if bf[i][0] in bnames]
    paired_b = {bf[i][0] for i, _, _ in pairs}
    missing = [bnames[x][0] for x in sorted(bnames) if x not in paired_b]
    if missing:
        print(f"  USA names without a match ({len(missing)}): " + " ".join(missing[:60]))

    # RELs
    rl = [f"# <module> <{a.id} .text offset> <{a.base_id} .text offset> <method>"]
    rtot = Counter()
    rfun = rall = 0
    for p in sorted((Path(a.disc) / "files" / "rels").glob("*.rel")):
        bp = Path(a.base_disc) / "files" / "rels" / p.name
        if not bp.exists():
            print("  no USA module for", p.name)
            continue
        r, br = Rel(p), Rel(bp)
        if r.id != br.id:
            print(f"  module id differs for {p.stem}: {br.id} -> {r.id}")
        rt, brt = r.code_sections()[0], br.code_sections()[0]
        rf = funcs_of(cfg / "rels" / f"{p.stem}.txt", (".text",))
        brf = funcs_of(bcfg / "rels" / f"{p.stem}.txt", (".text",))
        rd = lambda x, r=r, rt=rt: be32(r.data, rt.offset + x)
        brd = lambda x, br=br, brt=brt: be32(br.data, brt.offset + x)
        pr = align([fingerprint(brd, s, n) for s, n, _ in brf], [fingerprint(rd, s, n) for s, n, _ in rf],
                   [x[1] for x in brf], [x[1] for x in rf])
        for i, j, m in pr:
            rl.append(f"{r.id} {rf[j][0]:X} {brf[i][0]:X} {m}")
            rtot[m] += 1
        rfun += len(rf)
        rall += len(pr)
    (cfg / "rels_us_map.txt").write_text("\n".join(rl) + "\n", encoding="utf-8", newline="\n")
    print(f"{a.id} RELs: {rall}/{rfun} functions matched: {dict(rtot)}")


if __name__ == "__main__":
    main()
