#!/usr/bin/env python3
"""Writes the table of retail game files that setup checks a player's disc against
(src/setup/disc_files_<ID>.inc; docs/SETUP.md "Disc file check").

    py tools/gen_disc_files.py "US DATA/DATA" "PAL DATA/DATA" "JAPAN DATA/DATA" "KOREA DATA/DATA"

Each argument is an extracted game partition (sys/ + files/, Dolphin's "Extract Entire Disc" DATA
folder) of a clean retail disc (verify the image first, e.g. Dolphin: Properties > Verify). Every
file of the partition's file system (sys/fst.bin) gets one row: path, size and CRC-32 (zlib) of its
contents. No game data is stored, only these checksums.
"""
import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def fst_files(fst: bytes):
    count = struct.unpack_from(">I", fst, 8)[0]
    strings = 12 * count

    def name(i):
        o = strings + (struct.unpack_from(">I", fst, 12 * i)[0] & 0xFFFFFF)
        return fst[o:fst.index(b"\0", o)].decode("shift_jis")

    stack, out = [(count, "/")], []
    for i in range(1, count):
        while len(stack) > 1 and i >= stack[-1][0]:
            stack.pop()
        w, _, b = struct.unpack_from(">III", fst, 12 * i)
        p = stack[-1][1] + name(i)
        if w >> 24:
            stack.append((b, p + "/"))
        else:
            out.append((p, b))
    return out


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 1
    for arg in sys.argv[1:]:
        part = Path(arg)
        game_id = (part / "sys" / "boot.bin").read_bytes()[:6].decode("ascii")
        rows = []
        for p, size in fst_files((part / "sys" / "fst.bin").read_bytes()):
            data = (part / "files" / p.lstrip("/")).read_bytes()
            if len(data) != size:
                print(f"{part}: {p} is {len(data)} bytes, the FST says {size}: not a clean extraction")
                return 1
            rows.append((p, size, zlib.crc32(data)))
        dst = ROOT / "src" / "setup" / f"disc_files_{game_id}.inc"
        with open(dst, "w", encoding="utf-8", newline="\n") as o:
            o.write(f"// Generated by tools/gen_disc_files.py from a clean {game_id} rev 1 disc: path, size, CRC-32.\n")
            for p, size, h in rows:
                esc = p.replace("\\", "\\\\").replace('"', '\\"')
                o.write(f'{{"{esc}", {size:#x}u, {h:#010x}u}},\n')
        print(f"{dst}: {len(rows)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
