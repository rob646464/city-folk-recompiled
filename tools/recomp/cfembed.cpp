// Build tool: embeds files into a C++ source as character arrays.
//
//   cfembed <out.cpp> <namespace> <name>=<file> [<name>=<file> ...]
//
// For each file it defines `extern const char <name>[]` (NUL-terminated) and
// `extern const unsigned long long <name>Size`. Used for setup's inputs (src/setup/embedded.cpp).
#include <algorithm>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <iterator>
#include <string>
#include <vector>

int main(int argc, char** argv) {
    if (argc < 4) {
        std::fprintf(stderr, "usage: cfembed <out.cpp> <namespace> <name>=<file>...\n");
        return 2;
    }
    std::string out = "// Generated by tools/recomp/cfembed.cpp. Do not edit.\nnamespace " + std::string(argv[2]) + " {\n";
    for (int i = 3; i < argc; i++) {
        const std::string arg = argv[i];
        const size_t eq = arg.find('=');
        if (eq == std::string::npos) {
            std::fprintf(stderr, "cfembed: expected name=file, got %s\n", arg.c_str());
            return 2;
        }
        const std::string name = arg.substr(0, eq), path = arg.substr(eq + 1);
        std::string data;
        if (std::filesystem::is_directory(path)) {
            // A folder: its .txt files in name order, each after a line "\x01<stem>" (the REL maps,
            // config/<id>/rels; split again by setup/embedded.cpp).
            std::vector<std::filesystem::path> files;
            for (const auto& e : std::filesystem::directory_iterator(path))
                if (e.is_regular_file() && e.path().extension() == ".txt") files.push_back(e.path());
            std::sort(files.begin(), files.end());
            for (const auto& f : files) {
                std::ifstream in(f, std::ios::binary);
                data += "\x01" + f.stem().string() + "\n";
                data.append(std::istreambuf_iterator<char>(in), {});
                if (!data.empty() && data.back() != '\n') data += '\n';
            }
        } else {
            std::ifstream in(path, std::ios::binary);
            if (!in) {
                std::fprintf(stderr, "cfembed: cannot read %s\n", path.c_str());
                return 1;
            }
            data.assign(std::istreambuf_iterator<char>(in), {});
        }
        out += "extern const char " + name + "[] =\n\"";
        size_t col = 0;
        for (unsigned char ch : data) {
            if (ch >= 0x20 && ch < 0x7F && ch != '"' && ch != '\\' && ch != '?') {
                out += char(ch);
                col++;
            } else if (ch == '\n') {
                out += "\\n\"\n\"";
                col = 0;
                continue;
            } else {
                char buf[8];
                std::snprintf(buf, sizeof(buf), "\\%03o", ch);
                out += buf;
                col += 4;
            }
            if (col >= 120) {
                out += "\"\n\"";
                col = 0;
            }
        }
        out += "\";\n";
        out += "extern const unsigned long long " + name + "Size = " + std::to_string(data.size()) + "ull;\n";
    }
    out += "}\n";
    std::string old;
    if (std::ifstream prev{argv[1], std::ios::binary}) old.assign(std::istreambuf_iterator<char>(prev), {});
    if (old != out) std::ofstream(argv[1], std::ios::binary) << out;
    return 0;
}
